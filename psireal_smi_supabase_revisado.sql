create or replace function public.submit_smi_response(
  p_token uuid,
  p_patient_name text,
  p_patient_birth date,
  p_respostas jsonb,
  p_scores_modos jsonb,
  p_scores_dominios jsonb,
  p_modo_predominante text,
  p_alertas_clinicos jsonb default null
)
returns void
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_link public.patient_links%rowtype;
  v_psi_id text;
begin
  select *
  into v_link
  from public.patient_links
  where token = p_token
    and instrumento = 'SMI'
    and status = 'ativo'
    and (expires_at is null or expires_at > now())
  limit 1;

  if v_link.id is null then
    raise exception 'invalid or expired link';
  end if;

  select psi_id
  into v_psi_id
  from public.psis
  where user_id = v_link.psi_user_id;

  insert into public.respostas_smi (
    psi_user_id,
    patient_link_id,
    paciente_nome,
    paciente_nascimento,
    respostas,
    scores_modos,
    scores_dominios,
    modo_predominante,
    alertas_clinicos,
    psi_id,
    criado_em,
    status,
    created_at
  ) values (
    v_link.psi_user_id,
    v_link.id,
    coalesce(nullif(trim(p_patient_name), ''), v_link.patient_name),
    coalesce(p_patient_birth, v_link.patient_birth),
    p_respostas,
    p_scores_modos,
    p_scores_dominios,
    p_modo_predominante,
    p_alertas_clinicos,
    v_psi_id,
    now(),
    'novo',
    now()
  );

  update public.patient_links
  set status = 'respondido'
  where id = v_link.id;
end;
$function$;

revoke all on function public.submit_smi_response(uuid, text, date, jsonb, jsonb, jsonb, text, jsonb) from public;
grant execute on function public.submit_smi_response(uuid, text, date, jsonb, jsonb, jsonb, text, jsonb)
  to anon, authenticated;
