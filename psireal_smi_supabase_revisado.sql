create table if not exists public.respostas_smi (
  id bigint generated by default as identity primary key,
  psi_user_id uuid not null references public.psis(user_id) on delete cascade,
  patient_link_id uuid references public.patient_links(id) on delete set null,
  paciente_nome text not null,
  paciente_nascimento date,
  respostas jsonb not null,
  scores_modos jsonb,
  scores_dominios jsonb,
  modo_predominante text,
  alertas_clinicos jsonb,
  cruzamento_ysq jsonb,
  notas_psi text,
  status text not null default 'novo',
  psi_id text,
  criado_em timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists respostas_smi_psi_user_id_idx
  on public.respostas_smi (psi_user_id);
create index if not exists respostas_smi_created_at_idx
  on public.respostas_smi (created_at desc);

create or replace function public.sync_respostas_smi_legado()
returns trigger
language plpgsql
set search_path = public
as $function$
begin
  if NEW.criado_em is null then
    NEW.criado_em := NEW.created_at;
  end if;
  if NEW.psi_id is null and NEW.psi_user_id is not null then
    select psi_id into NEW.psi_id
    from public.psis
    where user_id = NEW.psi_user_id;
  end if;
  return NEW;
end;
$function$;

drop trigger if exists trg_sync_smi_legado on public.respostas_smi;
create trigger trg_sync_smi_legado
before insert or update on public.respostas_smi
for each row execute function public.sync_respostas_smi_legado();

alter table public.respostas_smi enable row level security;
grant select, update on public.respostas_smi to authenticated;

drop policy if exists "smi_select_own" on public.respostas_smi;
create policy "smi_select_own"
on public.respostas_smi for select to authenticated
using (psi_user_id = auth.uid());

drop policy if exists "smi_update_own" on public.respostas_smi;
create policy "smi_update_own"
on public.respostas_smi for update to authenticated
using (psi_user_id = auth.uid())
with check (psi_user_id = auth.uid());

