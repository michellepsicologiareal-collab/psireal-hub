create table if not exists public.perfil_psi_clinico (
  id bigint generated by default as identity primary key,
  psi_user_id uuid not null references public.psis(user_id) on delete cascade,
  ysq_scores jsonb not null default '{}',
  smi_scores jsonb not null default '{}',
  preenchido_em timestamptz not null default now(),
  versao_ysq text default 'YSQ-S3',
  versao_smi text default 'SMI-1.1',
  notas_pessoais text,
  n_preenchimentos integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists perfil_psi_clinico_psi_user_id_idx
  on public.perfil_psi_clinico (psi_user_id);

alter table public.perfil_psi_clinico enable row level security;
grant select, insert, update on public.perfil_psi_clinico to authenticated;

drop policy if exists "perfil_psi_select_own" on public.perfil_psi_clinico;
create policy "perfil_psi_select_own"
on public.perfil_psi_clinico for select to authenticated
using (psi_user_id = auth.uid());

drop policy if exists "perfil_psi_insert_own" on public.perfil_psi_clinico;
create policy "perfil_psi_insert_own"
on public.perfil_psi_clinico for insert to authenticated
with check (psi_user_id = auth.uid());

drop policy if exists "perfil_psi_update_own" on public.perfil_psi_clinico;
create policy "perfil_psi_update_own"
on public.perfil_psi_clinico for update to authenticated
using (psi_user_id = auth.uid())
with check (psi_user_id = auth.uid());

create table if not exists public.alertas_ativacao (
  id bigint generated by default as identity primary key,
  psi_user_id uuid not null references public.psis(user_id) on delete cascade,
  paciente_nome text not null,
  paciente_ref_id text,
  mecanismo text not null check (mecanismo in (
    'ressonancia_esquema',
    'complementaridade_modo',
    'gatilho_tema'
  )),
  nivel text not null check (nivel in ('moderado', 'alto', 'critico')),
  score numeric(5,2),
  esquemas_em_ressonancia text[],
  modos_complementares text[],
  temas_inferidos text[],
  temas_confirmados_psi text[],
  temas_confirmados_em timestamptz,
  titulo_alerta text not null,
  texto_alerta text not null,
  sugestao_clinica text,
  referencias text[],
  n_ocorrencias integer not null default 1,
  primeira_vez_em timestamptz not null default now(),
  ultima_vez_em timestamptz not null default now(),
  lido_em timestamptz,
  arquivado boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists alertas_psi_user_id_idx
  on public.alertas_ativacao (psi_user_id, arquivado, created_at desc);
create index if not exists alertas_paciente_idx
  on public.alertas_ativacao (psi_user_id, paciente_nome);

